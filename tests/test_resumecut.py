OBJS = [(30.0, 30.0), (100.0, 30.0), (30.0, 100.0)]   # левый нижний угол квадратов 20×20
SIDE = 20.0


def _square(x, y, z, lines, *, arc=False):
    lines.append(f"G1 X{x} Y{y} Z{z + 0.4}")           # переезд с подъёмом
    lines.append(f"G1 Z{z}")
    lines.append("G1 E.5 F1800")
    lines.append("G1 F3000")
    lines.append(";TYPE:Outer wall")
    if arc:
        # четверть окружности от (x+SIDE, y) до (x, y+SIDE) с центром в (x, y) — против часовой
        lines.append(f"G1 X{x + SIDE} Y{y} E.5")
        lines.append(f"G3 X{x} Y{y + SIDE} I{-SIDE} J0 E.8")
        lines.append(f"G1 X{x} Y{y} E.5")
    else:
        for px, py in ((x + SIDE, y), (x + SIDE, y + SIDE), (x, y + SIDE), (x, y)):
            lines.append(f"G1 X{px} Y{py} E.5")
    lines.append("G1 E-.5 F1800")


def make_gcode(path, *, layers=6, objs=OBJS, double=None, elegoo=True, labels=None, brim=False,
               arc_obj=None, flavor="klipper", m600_layer=None):
    """Файл в духе ElegooSlicer 1.5 для CC2. `double` — номер детали, напечатанной дважды;
    `labels` — 'orca' (комментарии), 'klipper' (EXCLUDE_OBJECT_*), 'm486' или None;
    `brim` — обводка каждой детали на первом слое с зазором 2 мм (сливает соседей у эвристики)."""
    L = ["; HEADER_BLOCK_START", "; generated by ElegooSlicer 1.5.3.4 on 2026-09-03 at 11:30:11",
         f"; total layer number: {layers}", "; HEADER_BLOCK_END", "",
         "; EXECUTABLE_BLOCK_START", "M73 P0 R100", "M106 S0", "M106 P2 S0", ";TYPE:Custom",
         "G90", "M104 S140", "M140 S60", "M190 S60 A", "M106 S0",
         "BED_MESH_CALIBRATE mesh_min=20,20 mesh_max=130,130 FROM_SLICER=1",
         "M204 S5000", "G28", "M109 S220", "M6211 A1 L200 T0 Q220 R220 S220", "T0"]
    if labels == "klipper":
        for i, (x, y) in enumerate(objs, 1):
            L.append(f"EXCLUDE_OBJECT_DEFINE NAME=cube_id_{i}_copy_0 CENTER={x + 10},{y + 10}")
    if elegoo:
        L += ["G180 S7", "G1 X127 Y-1.2 F20000", "G1 Z0.5 F900", "M73 P0 R99", "M109 S220", "M83",
              "G92 E0", "G1 E6 F150", "M106 S200", "G1 X87 E20 F1200", "G1 F6000", "G1 X82 E0.8",
              "M106 S0", "G180 S8"]
    L += ["G1 F20000", "G92 E0", f";LAYER_COUNT:{layers}", ";LAYER:0", "G90", "G21", "M83",
          "M106 P3 S200", "SET_PRESSURE_ADVANCE ADVANCE=0.03", "M106 P2 S0"]
    names = ["Куб", "Куб", "Шар"]
    for n in range(1, layers + 1):
        z = round(0.2 + 0.12 * (n - 1), 3)
        L += [";LAYER_CHANGE", f";Z:{z}", f";HEIGHT:{0.2 if n == 1 else 0.12}", ";BEFORE_LAYER_CHANGE",
              "G92 E0", f"M73 L{n}", f";LAYER:{n}", f"SET_PRINT_STATS_INFO TOTAL_LAYER={layers} CURRENT_LAYER={n}"]
        if n == 2:
            L += ["M106 S153", "M104 S215", "M140 S65"]
        if m600_layer and n == m600_layer:
            L.append("M600")
        L.append(f"M73 P{n * 100 // layers} R{100 - n * 100 // layers}")
        for i, (x, y) in enumerate(objs, 1):
            copies = 2 if double == i else 1
            for c in range(copies):
                if labels == "orca":
                    L.append(f"; printing object {names[i - 1]} id:{i} copy {c}")
                elif labels == "klipper":
                    L.append(f"EXCLUDE_OBJECT_START NAME=cube_id_{i}_copy_{c}")
                elif labels == "m486":
                    L.append(f"M486 S{i - 1}")
                if brim and n == 1:
                    L.append(";TYPE:Brim")
                    L.append(f"G1 X{x - 2} Y{y - 2} Z{z + 0.4}")
                    L.append(f"G1 Z{z}")
                    L.append("G1 E.5 F1800")
                    for px, py in ((x + SIDE + 2, y - 2), (x + SIDE + 2, y + SIDE + 2), (x - 2, y + SIDE + 2), (x - 2, y - 2)):
                        L.append(f"G1 X{px} Y{py} E.5")
                    L.append("G1 E-.5 F1800")
                _square(x, y, z, L, arc=(arc_obj == i))
                if labels == "orca":
                    L.append(f"; stop printing object {names[i - 1]} id:{i} copy {c}")
                elif labels == "klipper":
                    L.append(f"EXCLUDE_OBJECT_END NAME=cube_id_{i}_copy_{c}")
                elif labels == "m486":
                    L.append("M486 S-1")
    L += ["; filament end gcode ", ";===== CC2_END_GCODE ================", "M140 S0", "M83", "G92 E0",
          "G1 E-1.5 F1800", "G90", "G1 Z80 F20000", "G180 S9", "M104 S0", "M84", "M73 P100 R0",
          "; EXECUTABLE_BLOCK_END", "", "; layer_height = 0.12", "; printer_model = Elegoo Centauri Carbon 2",
          "; printable_area = 0x0,256x0,256x256,0x256", "; nozzle_temperature = 215",
          f"; gcode_flavor = {flavor}", f"; gcode_label_objects = {1 if labels else 0}"]
    path.write_text("\n".join(L), encoding="utf-8")
    return path


def _region_has_extrusion(text, x0, y0, x1, y1, from_layer):
    X = Y = None
    on = False
    for ln in text.split("\n"):
        if ln.startswith(";LAYER:"):
            on = int(ln[7:]) >= from_layer
            continue
        d = resumecut._parse(ln)
        if not d:
            continue
        nx = d.get("X", X)
        ny = d.get("Y", Y)
        if on and d.get("E", 0) > 0 and ("X" in d or "Y" in d) and nx is not None \
                and x0 - 1 <= nx <= x1 + 1 and y0 - 1 <= ny <= y1 + 1:
            return True
        X, Y = nx, ny
    return False


def _read_paths(data):
    assert data[:4] == b"PSTP"
    ver, hlen = struct.unpack_from("<HI", data, 4)
    header = json.loads(data[10:10 + hlen].decode("utf-8"))
    rec = struct.Struct("<fffffHBB")
    segs = [rec.unpack_from(data, 10 + hlen + i * rec.size) for i in range(header["count"])]
    return ver, header, segs


