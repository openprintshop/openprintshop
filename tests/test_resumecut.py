"""Допечатка с N-го слоя без сорвавшихся деталей — «Путь В» (app/resumecut.py, app/web/tools.py,
app/jobarchive.py, фазы печати в printwatch/store).

Проверяется на СИНТЕТИЧЕСКОМ g-code (три квадрата на столе, стартовый блок как у CC2):
  * детали находятся по первому слою эвристикой И по меткам слайсера (три диалекта), метки в
    приоритете и дают имена; брим, сливающий детали для эвристики, метками разделяется;
  * собранный файл начинается с нужного слоя, без калибровки стола и загрузки пластика, а
    сверка с исходником (та же, что зовёт ручка) проходит — экструзии совпадают побуквенно;
  * дуги G2/G3 растеризуются в траекториях и превью; стартовый блок Klipper собирается по
    общему образцу; стартовые переезды проверяются на пролёт над деталями;
  * бинарные траектории для 3D читаются обратно и содержат все ходы;
  * каждый отказ — с причиной; двойная копия детали — в предупреждениях;
  * ручки: 403 не-админу, путь вне разрешённых папок отвергается, разбор → сборка (задание с
    прогрессом) → траектории → скачивание → гейты → заливка → старт на фейковом принтере;
  * архив заданий: сторож копирует новый файл слайсера с названием из лога, лимит объёма чистит
    старое; фазы печати пишутся на переходах и подставляют слой паузы.
Реальный принтер не трогается.
"""
