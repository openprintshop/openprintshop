@pytest.mark.skipif(not os.getenv("RESUME_GOLDEN_GCODE"), reason="RESUME_GOLDEN_GCODE не задан")
def test_golden_real_file(tmp_path):
    """Живой g-code (путь в RESUME_GOLDEN_GCODE): разбор, сборка с середины, сверка и траектории.
    В репозиторий файл не кладём — это модели владельца, а репозиторий уезжает покупателям."""
    src = Path(os.environ["RESUME_GOLDEN_GCODE"])
    an = resumecut.analyze(src)
    assert an.supported and an.objects
    print(f"golden: {len(an.objects)} objects, mode={an.mode}, cross={an.cross}, separable={an.separable}")
    if not an.separable:
        # честный отказ эвристики (плита без меток с бримом/поддержками) — это состояние, не баг
        with pytest.raises(resumecut.ResumeUnavailable, match="не разделяются"):
            resumecut.build(src, an.first_layer + 1, [an.objects[0].id], tmp_path / "x.gcode")
        return
    layer = max(an.first_layer + 1, an.layers // 3)
    out = tmp_path / "golden.gcode"
    rep = resumecut.build(src, layer, [an.objects[0].id], out)
    assert rep.kept_objects == len(an.objects) - 1
    assert resumecut.verify(src, out, layer, [an.objects[0].id])["ok"]
    _ver, header, segs = _read_paths(resumecut.toolpaths(src))
    assert header["count"] == len(segs) > 1000
