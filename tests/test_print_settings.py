"""«С какими настройками отправлял на 3D-печать» (OpenTodo 8e8d4873).

Мастер режет модель руками в ElegooSlicer и заливает .gcode на принтер. Через неделю
вопрос «каким соплом и каким слоем это печаталось?» упирался в память: в журнале лежало
одно имя задания. Слайсер же пишет в конец gcode полный слепок настроек — тесты фиксируют,
что мы его читаем, храним под именем файла и находим ровно тогда, когда печать попадает
в журнал (в том числе когда принтер сообщает имя иначе, чем оно было при заливке).
"""
import pytest

from app import gcodemeta

# Кусок настоящего gcode ElegooSlicer 1.2 (шапка + хвост конфиг-блока), сокращённый до
# интересных ключей. Формат — семейства Bambu/Orca: `; ключ = значение`, значение на каждый
# из четырёх экструдеров хаба.
HEAD = """; HEADER_BLOCK_START
; generated by ElegooSlicer 1.2.0.19 on 2025-11-10 at 15:49:57
; total layer number: 240
; filament_density: 1.25,1.25,1.25,1.25
; max_z_height: 48.00
; HEADER_BLOCK_END
"""

TAIL = """; filament used [mm] = 1163.69, 1561.88
; filament used [g] = 3.50, 4.70
; total filament used [g] = 15.00
; estimated printing time (normal mode) = 41m 50s
; brim_type = auto_brim
; curr_bed_type = Textured PEI Plate
; enable_support = 0
; filament_flow_ratio = 0.98,0.98,0.98,0.98
; filament_max_volumetric_speed = 21,21,21,21
; filament_settings_id = "Elegoo PLA @ECC2";"Elegoo PLA @ECC2"
; filament_type = PLA;PLA;PLA;PLA
; hot_plate_temp = 60,60,60,60
; initial_layer_print_height = 0.2
; layer_height = 0.2
; nozzle_diameter = 0.4
; nozzle_temperature = 210,210,210,210
; pressure_advance = 0.024,0.024,0.024,0.024
; print_settings_id = 0.20mm Standard @Elegoo CC2 0.4 nozzle
; printer_settings_id = Elegoo Centauri Carbon 2 0.4 nozzle
; sparse_infill_density = 15%
; top_shell_layers = 5
; wall_loops = 2
"""


def test_parse_extracts_the_settings_that_matter():
    m = gcodemeta.parse_text(HEAD, TAIL)
    v = m["values"]
    assert v["nozzle_diameter"] == "0.4"
    assert v["layer_height"] == "0.2"
    assert v["sparse_infill_density"] == "15%"
    assert v["wall_loops"] == "2"
    assert v["print_settings_id"] == "0.20mm Standard @Elegoo CC2 0.4 nozzle"


def test_per_extruder_values_collapse():
    """«210,210,210,210» — это одна температура, а не четыре: у CC2 параметр пишется на слот."""
    v = gcodemeta.parse_text(HEAD, TAIL)["values"]
    assert v["nozzle_temperature"] == "210"
    assert v["filament_type"] == "PLA"
    assert v["filament_settings_id"] == "Elegoo PLA @ECC2"


def test_different_per_extruder_values_are_kept():
    """А вот РАЗНЫЕ значения по слотам — содержание двухцветной печати, их терять нельзя."""
    v = gcodemeta.parse_text(HEAD, "; filament_type = PLA;PETG;PLA;PLA\n")["values"]
    assert v["filament_type"] == "PLA, PETG"


def test_machine_values_become_words():
    v = gcodemeta.parse_text(HEAD, TAIL)["values"]
    assert v["enable_support"] == "нет"
    assert v["brim_type"] == "авто"


def test_summary_and_totals():
    m = gcodemeta.parse_text(HEAD, TAIL)
    assert m["slicer"].startswith("ElegooSlicer")
    assert m["layers"] == 240
    assert m["grams"] == 15.0
    assert m["minutes"] == pytest.approx(41.8, abs=0.1)
    assert gcodemeta.summary(m) == "сопло 0.4 · слой 0.2 · 15% · PLA"


def test_rows_keep_display_order():
    rows = gcodemeta.rows(gcodemeta.parse_text(HEAD, TAIL))
    keys = [r["key"] for r in rows]
    assert keys[0] == "nozzle_diameter" and keys[1] == "layer_height"
    assert all(r["value"] for r in rows)


def test_empty_value_does_not_swallow_the_next_line():
    """Ключ с ПУСТЫМ значением стоит ровно перед двумя самыми важными: «notes» перед
    «nozzle_diameter», «printer_notes» перед «printer_settings_id». Жадный \\s* после «=»
    съедал перевод строки и утаскивал следующую строку в значение — сопло молча пропадало
    из карточки. Поймано на настоящем gcode 3DBenchy, поэтому случай закреплён тестом."""
    tail = ("; notes = \n"
            "; nozzle_diameter = 0.4\n"
            "; printer_notes = \n"
            "; printer_settings_id = Elegoo Centauri Carbon 2 0.4 nozzle\n")
    v = gcodemeta.parse_text(HEAD, tail)["values"]
    assert v["nozzle_diameter"] == "0.4"
    assert v["printer_settings_id"] == "Elegoo Centauri Carbon 2 0.4 nozzle"


def test_not_a_slicer_file_gives_nothing():
    """Чужой файл не должен превращаться в «настройки»: пусто честнее выдумки."""
    assert gcodemeta.parse_text("", "G1 X10 Y10\nG1 Z0.2\n") == {}


def test_parse_file_reads_only_the_tail(tmp_path):
    """Конфиг-блок в конце файла: разбор не должен зависеть от размера задания."""
    p = tmp_path / "job.gcode"
    p.write_text(HEAD + "G1 X1\n" * 50000 + TAIL, encoding="utf-8")
    m = gcodemeta.parse_file(p)
    assert m["values"]["layer_height"] == "0.2"


def test_parse_bytes_matches_text():
    data = (HEAD + TAIL).encode("utf-8")
    assert gcodemeta.parse_bytes(data)["values"] == gcodemeta.parse_text(HEAD, TAIL)["values"]


# ── хранение снимка ────────────────────────────────────────────────────────────────────────
@pytest.mark.asyncio
async def test_snapshot_roundtrip(tmp_db):
    m = gcodemeta.parse_text(HEAD, TAIL)
    sid = await tmp_db.save_print_settings(
        "ECC2_0.4_Benchy_0.2.gcode", values=m["values"], slicer_name=m["slicer"],
        grams=m["grams"], minutes=m["minutes"], layers=m["layers"], uploaded=True,
        norm_name="ecc2_0.4_benchy_0.2")
    snap = await tmp_db.get_print_settings(sid)
    assert snap["values"]["nozzle_diameter"] == "0.4"
    assert snap["uploaded_at"] and snap["started_at"] is None


@pytest.mark.asyncio
async def test_upload_and_start_are_two_events_of_one_file(tmp_db):
    """Залили сегодня, запустили завтра: старт НЕ должен затирать разбор настроек."""
    name = "job.gcode"
    await tmp_db.save_print_settings(name, values={"layer_height": "0.2"}, uploaded=True)
    sid = await tmp_db.save_print_settings(name, start={"plate": "textured", "bedlevel": True},
                                           started=True)
    snap = await tmp_db.get_print_settings(sid)
    assert snap["values"]["layer_height"] == "0.2"      # разбор пережил старт
    assert snap["start"]["plate"] == "textured"
    assert snap["uploaded_at"] and snap["started_at"]


@pytest.mark.asyncio
async def test_found_by_normalized_name(tmp_db):
    """Принтер сообщает имя задания по-своему — иначе снимок не нашёлся бы в момент,
    когда печать попадает в журнал (ровно тогда он и нужен)."""
    await tmp_db.save_print_settings("Benchy.gcode", values={"layer_height": "0.2"},
                                     norm_name="benchy")
    assert await tmp_db.find_print_settings("Benchy.gcode") is not None
    assert await tmp_db.find_print_settings("/local/Benchy", "benchy") is not None
    assert await tmp_db.find_print_settings("другой файл", "другой") is None


@pytest.mark.asyncio
async def test_prune_keeps_snapshots_used_by_journal(tmp_db):
    """Чистка старых снимков не смеет забрать тот, на который ссылается печать в журнале."""
    keep = await tmp_db.save_print_settings("old.gcode", values={"layer_height": "0.12"})
    jid = await tmp_db.add_print_journal(label="old.gcode", plastic_id=None, plastic_name="",
                                         grams=10, minutes=30)
    await tmp_db.set_print_journal_fields(jid, settings_id=keep)
    for i in range(5):
        await tmp_db.save_print_settings(f"n{i}.gcode", values={"layer_height": "0.2"})

    await tmp_db.prune_print_settings(keep=2)
    assert await tmp_db.get_print_settings(keep) is not None
    assert len(await tmp_db.list_print_settings()) == 3      # 2 свежих + защищённый
