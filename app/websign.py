"""Подпись ссылок на медиа и версия файла в URL — фундамент веб-слоя.

Выделено из app/webapp.py волной 4 цикла 2 БЕЗ единой правки тел функций. Это самый маленький
кусок сквозного слоя, и взят он первым нарочно: на нём проверяется, что механика фасада
(webapp реэкспортирует перенесённые имена) работает и на фундаменте, а не только на доменном
блоке медиа из волны 3.

СЕКРЕТ И АЛГОРИТМ ПОДПИСИ НЕПРИКОСНОВЕННЫ. Подписанные ссылки уже разосланы клиентам и лежат
в старых сообщениях Telegram, а QR-этикетки со ссылкой /csample/{sid} наклеены на физические
образцы калибровки — перевыпустить их нельзя. Любое изменение токена, входной строки, функции
хеша или длины среза (12 символов) немедленно ломает ВСЕ выданные ссылки разом.

Модуль сознательно зависит только от app/config.py: webapp он не импортирует, поэтому
app/payments.py смог заменить отложенный `from .webapp import _sign` на обычный импорт
верхнего уровня — ребро цикла payments↔webapp не спрятано, а разорвано совсем.
"""
from __future__ import annotations

import hashlib
import hmac

from . import config


def _sign(s: str) -> str:
    """Короткая подпись id картинки токеном бота — чтобы превью нельзя было перебрать по id."""
    return hmac.new(config.BOT_TOKEN.encode(), s.encode(), hashlib.sha256).hexdigest()[:12]


def _file_ver(path) -> int:
    """Версия файла = mtime (сек). Подставляется в URL картинки как ?v=… — при замене
    файла версия меняется → меняется адрес → клиент качает свежее. 0, если файла нет.

    Путь может прийти из БД относительным (C2) — приводим через config.abs_data, иначе
    версия навсегда останется нулевой и браузер залипнет на старой картинке."""
    if not path:
        return 0
    try:
        return int(config.abs_data(path).stat().st_mtime)
    except (OSError, TypeError, ValueError):
        return 0
