"""Архив заданий печати: g-code, который ушёл на принтер, остаётся у нас.

Зачем: ElegooSlicer кладёт отправленный файл во временную папку и СТИРАЕТ её при следующей
нарезке — «допечатка со слоя» (app/resumecut.py) осталась без исходника уже дважды. Бот же
свои задания режет во временные каталоги и сносит их в finally. Здесь единственное место, куда
всё это складывается: `DATA_DIR/jobs/archive/<дата>_<название>.gcode` + индекс `index.json`.

Два входа:
  * `loop(bot)` — сторож: раз в минуту смотрит временные папки слайсера (`%LOCALAPPDATA%\\Temp\\
    elegooslicer_model` и `RESUME_GCODE_DIRS`) и копирует новое. Название берёт из лога слайсера
    (`start_upload` с modelName и временем печати), иначе из папки;
  * `register(path, name, source)` — задания самого бота (переслайс без детали, заливка из деска,
    допечатка со слоя) — копируются сюда же ТЕМ ЖЕ коммитом, что и заливка на принтер.

Гигиена: лимит объёма (`JOB_ARCHIVE_MAX_MB`, по умолчанию 5 ГБ) и срок (`JOB_ARCHIVE_DAYS`, 60):
старое удаляется, индекс правится. Архив лежит в DATA_DIR, но это кэш, а не данные студии:
офсайт-бэкап (app/backup.py) копирует только базу и до него не дотягивается.
"""
from __future__ import annotations

import asyncio
import json
import logging
import os
import re
import shutil
import time
from pathlib import Path

from . import config

log = logging.getLogger(__name__)

POLL_SEC = 60
MIN_BYTES = 10 * 1024
_HEAD_BYTES = 96 * 1024
_THUMB_RE = re.compile(r"; thumbnail begin (\d+)x(\d+) \d+\r?\n(.*?)\r?\n; thumbnail end", re.S)
_UPLOAD_RE = re.compile(r"^\[warning\]\s+(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)\.\d+.*?\"method\":\"start_upload\".*?"
                        r"\"modelName\":\"(.*?)\"(?:.*?\"printTime\":\"(.*?)\")?(?:.*?\"layerCount\":(\d+))?",
                        re.M)


def archive_dir() -> Path:
    return config.DATA_DIR / "jobs" / "archive"


def _index_path() -> Path:
    return archive_dir() / "index.json"


def slicer_temp_dirs() -> list[Path]:
    """Куда ElegooSlicer кладёт отправленный на принтер g-code + каталоги из RESUME_GCODE_DIRS."""
    out: list[Path] = []
    la = (os.getenv("LOCALAPPDATA") or "").strip()
    if la:
        out.append(Path(la) / "Temp" / "elegooslicer_model")
    for raw in (os.getenv("RESUME_GCODE_DIRS") or "").split(";"):
        raw = raw.strip().strip('"')
        if raw:
            out.append(Path(raw))
    return out


def slicer_log_dir() -> Path | None:
    ap = (os.getenv("APPDATA") or "").strip()
    return Path(ap) / "ElegooSlicer" / "log" if ap else None


def max_bytes() -> int:
    try:
        return int(os.getenv("JOB_ARCHIVE_MAX_MB") or 5120) * 1024 * 1024
    except ValueError:
        return 5120 * 1024 * 1024


def max_age_sec() -> int:
    try:
        return int(os.getenv("JOB_ARCHIVE_DAYS") or 60) * 86400
    except ValueError:
        return 60 * 86400


def head_info(p: Path) -> dict:
    """Справка по файлу из его шапки (без чтения 40 МБ): слои, время, превью, слайсер."""
    with p.open("rb") as f:
        text = f.read(_HEAD_BYTES).decode("utf-8", "replace")
    layers = re.search(r"total layer number:\s*(\d+)", text)
    m73 = re.search(r"^M73 P0 R(\d+)", text, re.M)
    gen = re.search(r"generated by ([^\n]+?) on ([^\n]+)", text)
    thumb = None
    m = _THUMB_RE.search(text)
    if m:
        thumb = "".join(l.strip().lstrip(";").strip() for l in m.group(3).split("\n"))
    return {"layers": int(layers.group(1)) if layers else None,
            "minutes": int(m73.group(1)) if m73 else None,
            "slicer": gen.group(1).strip() if gen else "",
            "sliced_at": gen.group(2).strip() if gen else "",
            "thumb": thumb}


def _load_index() -> list[dict]:
    try:
        data = json.loads(_index_path().read_text(encoding="utf-8"))
        return data if isinstance(data, list) else []
    except (OSError, ValueError):
        return []


def _save_index(items: list[dict]) -> None:
    archive_dir().mkdir(parents=True, exist_ok=True)
    tmp = _index_path().with_suffix(".json.tmp")
    tmp.write_text(json.dumps(items, ensure_ascii=False, indent=0), encoding="utf-8")
    tmp.replace(_index_path())


def _slug(name: str) -> str:
    s = re.sub(r"[^\w.\-]+", "_", name, flags=re.U).strip("_.")
    return s[:80] or "job"


def slicer_uploads(since: float | None = None) -> list[dict]:
    """Отправки из лога ElegooSlicer: (время, modelName, printTime, layerCount), новые последними."""
    d = slicer_log_dir()
    if not d or not d.is_dir():
        return []
    out = []
    logs = sorted(d.glob("debug_*.log*"), key=lambda p: p.stat().st_mtime)[-3:]
    for lp in logs:
        try:
            text = lp.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for m in _UPLOAD_RE.finditer(text):
            try:
                ts = time.mktime(time.strptime(m.group(1), "%Y-%m-%d %H:%M:%S"))
            except ValueError:
                continue
            if since is not None and ts < since:
                continue
            out.append({"ts": ts, "name": m.group(2), "print_time": m.group(3) or "",
                        "layers": int(m.group(4)) if m.group(4) else None})
    out.sort(key=lambda r: r["ts"])
    return out


def _name_for(p: Path, mtime: float, uploads: list[dict]) -> str:
    """Название задания: первая отправка слайсера ПОСЛЕ нарезки этого файла (в пределах часа)."""
    for u in uploads:
        if mtime - 120 <= u["ts"] <= mtime + 3600:
            return u["name"]
    return p.parent.parent.name if p.parent.name == "Metadata" else p.stem.lstrip(".")


def _known(items: list[dict], p: Path, st: os.stat_result) -> bool:
    for it in items:
        if it.get("src") == str(p) and int(it.get("src_mtime", 0)) == int(st.st_mtime) \
                and int(it.get("size", 0)) == st.st_size:
            return True
        if int(it.get("size", 0)) == st.st_size and it.get("src_mtime") and \
                abs(int(it["src_mtime"]) - int(st.st_mtime)) < 2:
            return True
    return False


def register(path: str | Path, name: str, *, source: str = "bot", copy: bool = True) -> dict | None:
    """Положить задание бота в архив (копией) и записать в индекс. Ошибки — в лог, не наружу."""
    p = Path(path)
    try:
        st = p.stat()
    except OSError:
        return None
    items = _load_index()
    if _known(items, p, st):
        return next((it for it in items if it.get("size") == st.st_size), None)
    try:
        info = head_info(p)
    except OSError:
        info = {}
    stamp = time.strftime("%Y%m%d_%H%M", time.localtime(st.st_mtime))
    dest = archive_dir() / f"{stamp}_{_slug(name)}.gcode"
    n = 1
    while dest.exists():
        n += 1
        dest = archive_dir() / f"{stamp}_{_slug(name)}_{n}.gcode"
    try:
        archive_dir().mkdir(parents=True, exist_ok=True)
        if copy:
            shutil.copy2(p, dest)
        else:
            shutil.move(str(p), dest)
    except OSError:
        log.warning("архив заданий: не скопировать %s", p, exc_info=True)
        return None
    entry = {"path": str(dest), "name": name, "source": source, "src": str(p),
             "src_mtime": int(st.st_mtime), "size": st.st_size, "added": int(time.time()),
             "layers": info.get("layers"), "minutes": info.get("minutes"),
             "slicer": info.get("slicer", ""), "sliced_at": info.get("sliced_at", "")}
    items.append(entry)
    _prune(items)
    _save_index(items)
    log.info("архив заданий: %s ← %s (%s)", dest.name, p.name, source)
    return entry


def _prune(items: list[dict]) -> None:
    """Старше срока или сверх лимита объёма — удалить, начиная с самого старого."""
    now = time.time()
    keep: list[dict] = []
    for it in items:
        p = Path(it.get("path", ""))
        if not p.is_file():
            continue
        if now - int(it.get("added", now)) > max_age_sec():
            try:
                p.unlink()
            except OSError:
                pass
            continue
        keep.append(it)
    keep.sort(key=lambda it: int(it.get("added", 0)))
    total = sum(int(it.get("size", 0)) for it in keep)
    while keep and total > max_bytes():
        it = keep.pop(0)
        total -= int(it.get("size", 0))
        try:
            Path(it["path"]).unlink()
        except OSError:
            pass
    items[:] = keep


def scan_once() -> int:
    """Один проход сторожа: новые файлы временных папок — в архив. Возвращает число новых."""
    items = _load_index()
    uploads = slicer_uploads(since=time.time() - 7 * 86400)
    added = 0
    for root in slicer_temp_dirs():
        if not root.is_dir():
            continue
        try:
            cands = list(root.rglob("*.gcode"))
        except OSError:
            continue
        for p in cands:
            try:
                st = p.stat()
            except OSError:
                continue
            if st.st_size < MIN_BYTES or time.time() - st.st_mtime < 20:
                continue        # ещё пишется или обрывок
            if _known(items, p, st):
                continue
            name = _name_for(p, st.st_mtime, uploads)
            if register(p, name, source="slicer"):
                added += 1
                items = _load_index()
    if not added:
        _prune(items)
        _save_index(items)
    return added


def entries(limit: int = 20) -> list[dict]:
    """Записи архива, новые первыми, только существующие файлы."""
    items = [it for it in _load_index() if Path(it.get("path", "")).is_file()]
    items.sort(key=lambda it: int(it.get("added", 0)), reverse=True)
    return items[:limit]


def find_by_job_name(norm: str, normalize) -> dict | None:
    """Запись архива по каноничному имени задания принтера (см. elegoo.normalize_job_name)."""
    if not norm:
        return None
    for it in entries(200):
        if normalize(it.get("name", "")) == norm or normalize(Path(it.get("path", "")).name) == norm:
            return it
    return None


async def loop(bot=None) -> None:
    """Фоновый сторож. Ошибки одного прохода не убивают цикл."""
    await asyncio.sleep(15)
    while True:
        try:
            n = await asyncio.to_thread(scan_once)
            if n:
                log.info("архив заданий: добавлено %d", n)
        except Exception:  # noqa: BLE001
            log.warning("архив заданий: проход не удался", exc_info=True)
        await asyncio.sleep(POLL_SEC)
