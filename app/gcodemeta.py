"""Настройки печати из .gcode (OpenTodo 8e8d4873 — «посмотреть, с какими настройками отправлял»).

Мастер режет модель в ElegooSlicer руками и заливает .gcode на принтер. Через неделю
вопрос «а каким слоем и каким соплом я это печатал?» упирался в память: в журнале печатей
лежало только имя задания, а сам gcode оставался на принтере.

Между тем слайсер сам пишет в конец файла ПОЛНЫЙ слепок настроек — сотни строк
`; ключ = значение` (это формат семейства Bambu/Orca, к которому относится и ElegooSlicer),
плюс сводку расхода и времени. Здесь мы его читаем: не весь (сотни ключей мастеру не нужны),
а осмысленную выжимку — то, чем печать реально отличается от соседней.

Читаем ХВОСТ файла: конфиг-блок идёт в конце, а сам gcode бывает и на 200 МБ.
"""
from __future__ import annotations

import logging
import re
from pathlib import Path

log = logging.getLogger(__name__)

# Сколько байт хвоста читаем: конфиг-блок ElegooSlicer ~60–90 КБ, берём с большим запасом,
# но не весь файл — иначе разбор 200-мегабайтного задания съел бы память и время.
TAIL_BYTES = 512 * 1024
HEAD_BYTES = 8 * 1024              # шапка: генератор, число слоёв, высота

# Ключ → (человеческое имя, единица). Порядок = порядок показа в карточке печати:
# сначала «чем печатали» (сопло/слой), потом плотность/стенки, потом филамент и температуры.
FIELDS: tuple[tuple[str, str, str], ...] = (
    ("nozzle_diameter", "Сопло", "мм"),
    ("layer_height", "Высота слоя", "мм"),
    ("initial_layer_print_height", "Первый слой", "мм"),
    ("wall_loops", "Периметры", ""),
    ("sparse_infill_density", "Заполнение", ""),
    ("sparse_infill_pattern", "Узор заполнения", ""),
    ("top_shell_layers", "Верхних слоёв", ""),
    ("bottom_shell_layers", "Нижних слоёв", ""),
    ("enable_support", "Поддержки", ""),
    ("brim_type", "Кайма", ""),
    ("filament_type", "Материал", ""),
    ("filament_settings_id", "Профиль филамента", ""),
    ("nozzle_temperature", "Температура сопла", "°C"),
    ("hot_plate_temp", "Стол", "°C"),
    ("curr_bed_type", "Пластина", ""),
    ("filament_flow_ratio", "Поток", ""),
    ("pressure_advance", "Pressure Advance", ""),
    ("filament_max_volumetric_speed", "Макс. объёмный расход", "мм³/с"),
    ("outer_wall_speed", "Скорость наружного периметра", "мм/с"),
    ("print_settings_id", "Профиль процесса", ""),
    ("printer_settings_id", "Профиль принтера", ""),
)
_WANT = {k for k, _, _ in FIELDS}

# [^\S\n] = пробел/таб, но НЕ перевод строки. Обычный \s здесь ломался: у ключа с пустым
# значением («; notes = ») \s* после «=» съедал перевод строки, и в значение попадала
# СЛЕДУЮЩАЯ строка целиком — вместе с её ключом. Так молча терялись «nozzle_diameter»
# (идёт сразу за «notes») и «printer_settings_id» (сразу за «printer_notes»), то есть ровно
# то, ради чего разбор и затевался. Поймано на настоящем gcode 3DBenchy.
_KV_RE = re.compile(r"^;[^\S\n]*([a-z0-9_]+)[^\S\n]*=[^\S\n]*(.*)$", re.I | re.M)
_TOTAL_G_RE = re.compile(r"total filament used \[g\]\s*=\s*([0-9.]+)")
_TIME_RE = re.compile(r"estimated printing time \(normal mode\)\s*=\s*([0-9hms\s]+)")
_LAYERS_RE = re.compile(r"total layer number:\s*(\d+)")
_GEN_RE = re.compile(r"generated by ([^\n]+?) on ", re.I)


def _dedupe(value: str) -> str:
    """«210,210,210,210» → «210», «PLA;PLA;PLA;PLA» → «PLA».

    Слайсер пишет параметр НА КАЖДЫЙ экструдер (у CC2 их 4 по числу слотов хаба). Когда
    значения одинаковы — это одно число, и показывать его четыре раза незачем. Разные
    (двухцветная печать) — оставляем перечисление: там это и есть содержание."""
    txt = (value or "").strip().strip('"')
    if not txt:
        return ""
    for sep in (";", ","):
        if sep in txt:
            parts = [p.strip().strip('"') for p in txt.split(sep)]
            uniq = list(dict.fromkeys(p for p in parts if p))
            if not uniq:
                return ""
            return uniq[0] if len(uniq) == 1 else ", ".join(uniq)
    return txt


def _pretty(key: str, value: str) -> str:
    """Значения, которые в gcode записаны машинно, — словами мастера."""
    if key == "enable_support":
        return "да" if value in ("1", "true") else "нет"
    if key == "brim_type":
        return {"auto_brim": "авто", "no_brim": "нет", "outer_only": "снаружи",
                "inner_only": "внутри", "outer_and_inner": "снаружи и внутри"}.get(value, value)
    return value


def _minutes(text: str) -> float | None:
    """«41m 50s» / «1h 12m» → минуты."""
    h = re.search(r"(\d+)\s*h", text)
    m = re.search(r"(\d+)\s*m", text)
    s = re.search(r"(\d+)\s*s", text)
    if not (h or m or s):
        return None
    total = (int(h.group(1)) * 60 if h else 0) + (int(m.group(1)) if m else 0)
    return round(total + (int(s.group(1)) / 60 if s else 0), 1)


def parse_text(head: str, tail: str) -> dict:
    """Выжимка настроек из шапки и хвоста gcode. Пустой словарь — файл не от слайсера."""
    out: dict = {"values": {}, "raw": {}}
    for m in _KV_RE.finditer(tail):
        key, val = m.group(1), _dedupe(m.group(2))
        if key in _WANT and val:
            out["raw"][key] = val
    if not out["raw"]:
        return {}
    out["values"] = {k: _pretty(k, v) for k, v in out["raw"].items()}
    gen = _GEN_RE.search(head)
    if gen:
        out["slicer"] = gen.group(1).strip()
    layers = _LAYERS_RE.search(head)
    if layers:
        out["layers"] = int(layers.group(1))
    grams = _TOTAL_G_RE.search(tail)
    if grams:
        out["grams"] = float(grams.group(1))
    t = _TIME_RE.search(tail)
    if t:
        out["minutes"] = _minutes(t.group(1))
    return out


def parse_file(path: str | Path) -> dict:
    """То же по файлу: читаем шапку и хвост, не втягивая гигабайты в память.

    Блокирующая (диск) — звать в asyncio.to_thread. Любой сбой чтения → {} (настройки
    просто не покажутся; терять из-за этого саму заливку на принтер нельзя)."""
    p = Path(path)
    try:
        size = p.stat().st_size
        with p.open("rb") as f:
            head = f.read(HEAD_BYTES).decode("utf-8", "ignore")
            if size > TAIL_BYTES:
                f.seek(-TAIL_BYTES, 2)
            tail = f.read().decode("utf-8", "ignore")
        return parse_text(head, tail)
    except OSError:
        log.debug("gcodemeta: не прочитать %s", p, exc_info=True)
        return {}


def parse_bytes(data: bytes) -> dict:
    """То же по уже прочитанному содержимому (заливка на принтер приходит байтами)."""
    try:
        head = data[:HEAD_BYTES].decode("utf-8", "ignore")
        tail = data[-TAIL_BYTES:].decode("utf-8", "ignore")
        return parse_text(head, tail)
    except Exception:  # noqa: BLE001
        log.debug("gcodemeta: не разобрать содержимое", exc_info=True)
        return {}


def rows(meta: dict) -> list[dict]:
    """Выжимка → список строк для интерфейса: [{key, label, value, unit}] в порядке FIELDS."""
    vals = (meta or {}).get("values") or {}
    return [{"key": k, "label": label, "value": vals[k], "unit": unit}
            for k, label, unit in FIELDS if vals.get(k)]


def summary(meta: dict) -> str:
    """Одна строка для списка: «0.4 мм · слой 0.2 · 15% · PLA»."""
    v = (meta or {}).get("values") or {}
    parts = []
    if v.get("nozzle_diameter"):
        parts.append(f"сопло {v['nozzle_diameter']}")
    if v.get("layer_height"):
        parts.append(f"слой {v['layer_height']}")
    if v.get("sparse_infill_density"):
        parts.append(v["sparse_infill_density"])
    if v.get("filament_type"):
        parts.append(v["filament_type"])
    return " · ".join(parts)
