"""Параметры стола принтера ОДНИМ объектом — вместо констант, размазанных по модулям.

ЗАЧЕМ. Порог «размер стола» решает не только «мультиплейт ли раскладка», но и ДЕДУПИТЬ ЛИ
наложенные копии (см. geometry._dedup_piled_insts / fastmeasure._aggregate). Один и тот же
набор при разных столах даёт разный объём и разное число деталей — то есть разные граммы и
разную цену. Пока стол зашит константой, принтер с другим столом считается по чужому числу.
Этот модуль — единственное место, где числа стола живут; дальше они ездят ПАРАМЕТРОМ.

ЧИСЛА ПЕРЕНЕСЕНЫ КАК ЕСТЬ, из сегодняшнего кода (ничего не округлено и не «улучшено»):

  • xy_mm 256.0            — slicer._BED_FULL_MM, фолбэк slicer.bed_size, fastcalc/texts;
                             реальная печатная область CC2 по XY;
  • z_mm 256.0             — фолбэк printable_height в slicer.bed_size;
  • pile_ratio 0.75        — geometry._PILE_RATIO == fastmeasure._PILE_RATIO. Разброс центров
                             одинаковых экземпляров < pile_ratio × размер экземпляра ⇒ куча
                             копий-дублей. Калибровка по реальным файлам: динозавр (2 копии)
                             ratio ≈ 0.49, осьминог (60 звеньев) ≈ 2.2;
  • arrange_gap_mm 8.0     — fastmeasure.estimate_plates: зазор между деталями (arrange
                             ElegooSlicer держит ~5-8 мм с учётом юбки);
  • arrange_margin_mm 10.0 — fastmeasure.estimate_plates: отступ от краёв стола.

  • fit_xy_mm (свойство) 250.0 — geometry._BED_MM == fastmeasure._BED_MM == slicer._BED_MM:
                             «умещается на столе», стол минус запас на края. В коде это число
                             и было записано как «CC2 ~256, запас на края» ⇒ здесь оно ровно
                             xy_mm − EDGE_MARGIN_MM = 256.0 − 6.0 = 250.0 (точно, без потери
                             в float), а не отдельная константа. Так порог едет за столом
                             принтера, а не остаётся числом CC2 на любом железе.

DEFAULT_BED — ровно сегодняшнее поведение. Все места, куда BedSpec протащен параметром,
по умолчанию берут его, поэтому вызовы, которые стол не передают, считают как раньше.
"""
from __future__ import annotations

import dataclasses
from dataclasses import dataclass
from pathlib import Path

# Запас на края стола: разница между реальной печатной областью (256) и порогом «умещается»
# (250), который стоял в geometry/fastmeasure/slicer. Не подгонка — так этот порог и был
# задокументирован в slicer.py: «умещается на столе» (CC2 ~256), запас на края.
EDGE_MARGIN_MM = 6.0


@dataclass(frozen=True)
class BedSpec:
    """Стол принтера: габариты + параметры раскладки/дедупа, зависящие от его размера.

    Неизменяемый и пикуемый — уезжает в cpupool-воркеры вместе с задачей подготовки геометрии.
    """

    xy_mm: float = 256.0             # печатная область по XY (меньшая сторона прямоугольного стола)
    z_mm: float = 256.0              # печатная высота
    pile_ratio: float = 0.75         # порог «копии лежат кучей» (× размер экземпляра)
    arrange_gap_mm: float = 8.0      # зазор между деталями при авто-раскладке
    arrange_margin_mm: float = 10.0  # отступ от краёв стола при авто-раскладке

    @property
    def fit_xy_mm(self) -> float:
        """Порог «деталь/раскладка умещается на столе», мм: стол минус запас на края.

        По нему решается: склеивать ли детали в один меш, мультиплейт ли раскладка (а значит —
        дедупить ли наложенные копии) и физична ли раскладка по Z. При дефолтном столе даёт
        РОВНО прежние 250.0."""
        return max(1.0, float(self.xy_mm) - EDGE_MARGIN_MM)

    @classmethod
    def from_machine_profile(cls, machine_profile: str | Path | None,
                             **overrides: float) -> "BedSpec":
        """BedSpec по профилю машины принтера (printable_area/printable_height).

        Читает стол существующей slicer.bed_size (импорт ленивый: slicer сам зависит от
        bedspec). Профиль не задан / не разобрался — bed_size отдаёт консервативный CC2,
        то есть получаем DEFAULT_BED. overrides — точечная подмена полей (pile_ratio и т.п.)."""
        if not machine_profile:
            return cls(**overrides)  # type: ignore[arg-type]
        try:
            from . import slicer
            xy, z = slicer.bed_size(machine_profile)
        except Exception:  # noqa: BLE001 — стол не прочитался: считаем как раньше, а не падаем
            return cls(**overrides)  # type: ignore[arg-type]
        return cls(xy_mm=float(xy), z_mm=float(z), **overrides)  # type: ignore[arg-type]


# Сегодняшние числа. Значение по умолчанию для всех протащенных параметров.
DEFAULT_BED = BedSpec()


def bed_tag(bed: BedSpec) -> str:
    """Отпечаток стола для имени файла кэша — ОДИН формат на весь проект.

    Стол решает не только «мультиплейт ли раскладка», но и ДЕДУПИТЬ ЛИ наложенные копии
    (geometry._dedup_piled_insts / fastmeasure._aggregate) — то есть от него зависят и граммы
    с ценой, и число деталей в превью/3D-вьюере. Без стола в ключе два принтера с разными
    столами делили бы одну запись и отдавали друг другу чужие цифры и чужие картинки.
    Берём ВЕСЬ BedSpec, а не только читаемые сегодня поля: лишний промах кэша дешевле молча
    отданной чужой сметы. Жил приватным в fastcalc._bed_tag — поднят сюда, чтобы превью, GLB
    и замеры метили ключи ОДИНАКОВО (иначе форматы разъедутся при первой же правке)."""
    return "b" + "-".join(f"{float(v):g}" for v in dataclasses.astuple(bed))


def bed_key_suffix(bed: BedSpec) -> str:
    """Хвост ключа кэша: ПУСТО для дефолтного стола, «_b256-256-…» для любого другого.

    Почему условно, а не всегда (как в fastcalc, где кэш замеров молодой): ключи превью/
    геометрии/GLB уже прогреты на боевой машине (сотни файлов, ~650 МБ, самый дорогой —
    разбор .3mf + дециация + экспорт GLB). Для DEFAULT_BED результат НЕ изменился ни на бит,
    поэтому старые записи остаются верными и версию ключа бампать не за что; принтер с другим
    столом получает собственное имя файла и никогда не увидит чужую картинку. Это и даёт
    требование «при одном принтере (CC2) поведение прежнее» бесплатно."""
    return "" if bed == DEFAULT_BED else "_" + bed_tag(bed)
